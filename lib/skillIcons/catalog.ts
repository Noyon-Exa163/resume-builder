/**
 * The curated list of skills that get an icon next to them on a resume.
 *
 * Each entry is `[iconSlug, ...spellings]`:
 *  - `iconSlug` is the icon's folder name in https://github.com/glincker/thesvg
 *    and the file name of its pre-rendered PNG in `public/skill-icons/`
 *    (see scripts/buildSkillIcons.ts).
 *  - the spellings are every way people write that skill. Case, spaces and
 *    punctuation are ignored when matching, so "Node.js", "NodeJS" and
 *    "nodejs" are all one spelling. The slug itself always matches too.
 *
 * Matching is exact on purpose: a skill with no entry here gets no icon,
 * never a guess. To add a skill, add a line here and run
 * `npm run build:skill-icons` (it also refreshes the PNGs).
 *
 * Some entries deliberately point a closely related tool at its parent
 * brand's icon (e.g. "Docker Compose" uses the Docker whale).
 */
